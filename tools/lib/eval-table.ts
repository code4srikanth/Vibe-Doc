// The evaluation table (docs/evaluation): what npm run review writes. Judge 1 is the AI's answer; Judge 2 is a clinician's,
// read from a file the tool never writes, so regenerating a table cannot change it.
import type { Edit } from "../../src/model/edits.ts";
import type { Intended, Judgement, Match } from "../../server/judge.ts";

/** The views a table shows, in column order. */
export const TABLE_VIEWS = [
  { id: "exterior", heading: "External" },
  { id: "optic_section_lens", heading: "Slit view 1 (optic section, lens)" },
  { id: "retroillumination", heading: "Slit view 2 (retroillumination)" }
] as const;

export interface EvalRow {
  id: string;
  description: string;
  prompt: string;
  intended: Intended;
  edits: Edit[];
  diagnosis: string;
  signs: string[];
  valid: boolean;
  steps: number;
  /** Why this build may be weak, whatever `valid` says. */
  flags: string[];
  /** Image file for each view, relative to the table. Absent if the render failed. */
  images: Record<string, string>;
  /** Muse Image's edit of the healthy eye's render for the same prompt, relative to the table. An illustration only: no judge sees it. */
  edited?: { image?: string; prompt: string; error?: string };
  judge?: Judgement;
  match?: Match;
  /** What stopped the run, if something did. */
  error?: string;
}

export interface ClinicalReview {
  diagnosis?: string;
  severity?: string;
  realism?: number;
  usable?: "yes" | "with changes" | "no";
  notes?: string;
  role?: string;
  date?: string;
}

const cell = (s: string) => s.replace(/\s+/g, " ").replaceAll("|", "\\|").trim();
const thumb = (file: string | undefined, alt: string) => file ? `[<img src="${file}" width="160" alt="${cell(alt)}">](${file})` : "Not rendered";

const illustration = (file: string | undefined, alt: string) => file ? thumb(file, alt) : "Not generated";

/** A build can pass every range check and still barely show the disease: one saved run set a single spoke location. */
export function weakBuild(r: Pick<EvalRow, "valid" | "signs" | "edits" | "steps">, maxSteps = 30): string[] {
  return [
    !r.valid && "not valid",
    r.steps >= maxSteps && "hit the step limit",
    !r.signs.length && "no signs returned",
    r.edits.length < 2 && `only ${r.edits.length} edit${r.edits.length === 1 ? "" : "s"}`
  ].filter((x): x is string => !!x);
}

function judge1(r: EvalRow): string {
  if (r.error) return cell(`Not judged: ${r.error}`);
  if (!r.judge) return "Not judged";
  const yes = (b: boolean | null | undefined) => b === null || b === undefined ? "n/a" : b ? "match" : "no match";
  return cell(`**${r.judge.diagnosis}**, ${r.judge.severity}. Diagnosis: ${yes(r.match?.diagnosis)}. Severity: ${yes(r.match?.severity)}. Realism ${r.judge.realism}/5. ${r.judge.note} (${r.judge.model}, ${r.judge.date})`);
}

function judge2(c: ClinicalReview | undefined): string {
  if (!c) return "Pending";
  const parts = [
    c.diagnosis && `**${c.diagnosis}**${c.severity ? `, ${c.severity}` : ""}.`,
    c.realism !== undefined && `Realism ${c.realism}/5.`,
    c.usable && `Usable for teaching: ${c.usable}.`,
    c.notes,
    (c.role || c.date) && `(${[c.role, c.date].filter(Boolean).join(", ")})`
  ];
  return cell(parts.filter(Boolean).join(" "));
}

export function buildTable(title: string, rows: EvalRow[], clinical: Record<string, ClinicalReview>): string {
  const reviewed = rows.filter(r => clinical[r.id]).length;
  const status = reviewed
    ? `Clinical review covers ${reviewed} of ${rows.length} rows.`
    : "No clinical review has happened yet.";
  const lines = [
    `# ${title}`, "",
    `${status} Judge 1 is an AI opinion on the renders, not clinical validation. The Muse Image column is an AI-generated illustration, edited from the healthy eye's render to fit the same prompt. It is not a clinical reference, and no judge sees it. Generated by \`npm run review\`.`, "",
    `| ID | Short description | Prompt | Muse Image from normal eye (AI illustration) | ${TABLE_VIEWS.map(v => v.heading).join(" | ")} | Judge 1 (AI) | Judge 2 (Clinical) |`,
    `|---|---|---|---|${TABLE_VIEWS.map(() => "---").join("|")}|---|---|`,
    ...rows.map(r => `| ${r.id} | ${cell(r.description)}${r.flags.length ? ` (weak build: ${r.flags.join(", ")})` : ""} | ${cell(r.prompt)} | ${illustration(r.edited?.image, `${r.id} Muse Image from normal eye`)} | ${TABLE_VIEWS.map(v => thumb(r.images[v.id], `${r.id} ${v.heading}`)).join(" | ")} | ${judge1(r)} | ${judge2(clinical[r.id])} |`),
    ""
  ];
  return lines.join("\n");
}

const codeOf = (random: () => number) => `R${Math.floor(random() * 0xffff).toString(16).padStart(4, "0").toUpperCase()}`;

/** A code for each row, kept once given so a review in progress stays valid. */
export function blindCodes(rows: EvalRow[], known: Record<string, string> = {}, random = Math.random): Record<string, string> {
  const codes = { ...known };
  const used = new Set(Object.values(codes));
  for (const r of rows) {
    if (codes[r.id]) continue;
    let code = codeOf(random);
    while (used.has(code)) code = codeOf(random);
    used.add(code);
    codes[r.id] = code;
  }
  return codes;
}

/** The clinician's sheet: codes and images in shuffled order, with no description, prompt or AI answer. */
export function buildBlindSheet(rows: EvalRow[], codes: Record<string, string>, random = Math.random): { markdown: string; copies: { from: string; to: string }[] } {
  const order = rows.filter(r => TABLE_VIEWS.some(v => r.images[v.id])).map(r => ({ r, k: random() })).sort((a, b) => a.k - b.k).map(x => x.r);
  const copies: { from: string; to: string }[] = [];
  const body = order.map(r => {
    const code = codes[r.id];
    const images = TABLE_VIEWS.map((v, i) => {
      if (!r.images[v.id]) return "Not rendered";
      const to = `${code}-${i + 1}.png`;
      copies.push({ from: r.images[v.id], to });
      return thumb(to, `${code} view ${i + 1}`);
    });
    return `| ${code} | ${images.join(" | ")} | | | | |`;
  });
  const markdown = [
    "# Blind review sheet", "",
    "For each code, write the diagnosis and severity you see, realism from 1 to 5, and whether it is usable for teaching (yes, with changes, no).", "",
    `| Code | ${TABLE_VIEWS.map(v => v.heading).join(" | ")} | Diagnosis, severity | Realism | Usable | Notes |`,
    `|---|${TABLE_VIEWS.map(() => "---").join("|")}|---|---|---|---|`,
    ...body,
    ""
  ].join("\n");
  return { markdown, copies };
}
