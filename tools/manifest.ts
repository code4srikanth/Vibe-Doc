// Writes eye-model/manifest.json: the index agents read first (like package.xml),
// so they can find the right component or disease without opening every file.
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { MODEL, readJsonDir } from "./lib/library.ts";
import type { Case, ComponentType, Disease, EyeComponent, Variant } from "../src/model/generated.ts";
import { FACETS } from "../src/model/library.ts";

const components = readJsonDir<EyeComponent>("normal").map(({ file, data: c }) => ({
  id: c.id,
  type: c.type,
  summary: c.summary,
  file,
  properties: Object.fromEntries(FACETS.filter(f => c[f]).map(f => [f, Object.keys(c[f]!)])),
  visible_in: c.clinical?.visible_in ?? [],
  confidence: c.provenance.confidence
}));

const manifest = {
  note: "Generated by tools/manifest.ts (npm run manifest). Do not edit by hand.",
  components,
  types: readJsonDir<ComponentType>("schema/types", ".type.json").map(({ file, data }) => ({ type: data.type, description: data.description, file })),
  diseases: readJsonDir<Disease>("diseases").map(({ file, data: d }) => ({ id: d.id, name: d.name, summary: d.summary, affects: d.affects, grades: Object.keys(d.grades), params: Object.keys(d.params ?? {}), file })),
  variants: readJsonDir<Variant>("variants").map(({ file, data }) => ({ id: data.id, summary: data.summary, file })),
  cases: readJsonDir<Case>("cases").map(({ file, data }) => ({ id: data.id, title: data.title, diseases: data.diseases.map(d => `${d.id}@${d.grade}`), file }))
};

writeFileSync(join(MODEL, "manifest.json"), JSON.stringify(manifest, null, 2) + "\n");
console.log(`manifest: ${components.length} components, ${manifest.diseases.length} diseases, ${manifest.variants.length} variants, ${manifest.cases.length} cases`);
