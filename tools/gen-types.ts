// Generates TypeScript types from the eye-model JSON Schemas, so the renderer,
// tools and agents share one source of truth. Output: src/model/generated.ts
import { compileFromFile } from "json-schema-to-typescript";
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { ROOT } from "./lib/library.ts";

const schemaDir = join(ROOT, "eye-model", "schema");
const files = ["component", "disease", "case", "rules", "type", "variant"];

const parts = await Promise.all(files.map(f =>
  compileFromFile(join(schemaDir, `${f}.schema.json`), {
    cwd: schemaDir,
    bannerComment: "",
    declareExternallyReferenced: f === "component" || f === "disease",
    additionalProperties: false,
    style: { singleQuote: false }
  })
));

const header = "// Generated by tools/gen-types.ts from eye-model/schema. Do not edit by hand; run `npm run gen:types`.\n\n";
// Each compile repeats shared types (Quantity, Patch); keep the first declaration only.
const seen = new Set<string>();
const body = parts.join("\n").split(/\n(?=export )/).filter(block => {
  const name = /^export (?:interface|type) (\w+)/.exec(block.trim())?.[1];
  if (!name) return true;
  if (seen.has(name)) return false;
  seen.add(name);
  return true;
}).join("\n");
writeFileSync(join(ROOT, "src", "model", "generated.ts"), header + body);
console.log(`Generated ${seen.size} types -> src/model/generated.ts`);
